function fields(inputs, base = "event.parameters", tuple = false, prefix = "") {
  return inputs.flatMap((p, i) => {
    const expr = tuple ? `${base}[${i}]` : `${base}[${i}].value`;
    const name = prefix + p.name;
    if (p.type === "tuple") return fields(p.components, expr + ".toTuple()", true, name + "_");
    const rank = (p.type.match(/\[/g) || []).length;
    if (rank > 2 || (rank === 2 && !/^u?int/.test(p.type))) throw Error("Unsupported event matrix " + p.type);
    const array = p.type.includes("["),
      t = p.type.split("[")[0];
    let gql, convert;
    if (t === "address") {
      gql = "Bytes";
      convert = array ? "toAddressArray().map<Bytes>((value) => value)" : "toAddress()";
    } else if (t.startsWith("bytes")) {
      gql = "Bytes";
      convert = array ? "toBytesArray()" : "toBytes()";
    } else if (t === "bool") {
      gql = "Boolean";
      convert = array ? "toBooleanArray()" : "toBoolean()";
    } else if (/^u?int/.test(t)) {
      gql = "BigInt";
      convert = rank === 2 ? null : array ? "toBigIntArray()" : "toBigInt()";
    } else throw Error("Unsupported event type " + p.type);
    return [
      {
        name: name === "id" ? "depositId" : name,
        gql: array ? `[${gql}!]` : gql,
        expr: rank === 2 ? `flattenIntegerMatrix(${expr})` : `${expr}.${convert}`
      }
    ];
  });
}
