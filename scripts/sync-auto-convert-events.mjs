function type(p) {
  return p.type === "tuple" ? "(" + p.components.map(type).join(",") + ")" : p.type;
}
export function signature(e) {
  return e.name + "(" + e.inputs.map((p) => (p.indexed ? "indexed " : "") + type(p)).join(",") + ")";
}
