handler += `
function flattenIntegerMatrix(value: ethereum.Value): Array<BigInt> {
  const rows = value.toArray();
  const result = new Array<BigInt>();
  for (let row = 0; row < rows.length; ++row) {
    const columns = rows[row].toBigIntArray();
    for (let column = 0; column < columns.length; ++column) result.push(columns[column]);
  }
  return result;
}
`;
